// Exports an allowlisted slice of the vault into a self-contained static site (default: ./site) for Vercel.
// Usage: node export-static.mjs [--vault "D:\ObsidianVault\Hudební produkce"] [--out site] [--exclude "workshop videos,ai-memory-vault"]
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildIndex, DEFAULT_IGNORE, indexPayload, notePayload, tagsPayload, graphPayload } from './lib/vault-index.mjs';
import { scrubDeep } from './lib/scrub-paths.mjs';
import { loadPresets, loadBuild } from './lib/presets-data.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const arg = (name, def) => { const i = process.argv.indexOf('--' + name); return i > 0 ? process.argv[i + 1] : def; };

const VAULT = path.resolve(arg('vault', 'D:\\ObsidianVault\\Hudební produkce'));
const OUT = path.resolve(HERE, arg('out', 'site'));
const EXCLUDE = arg('exclude', 'workshop videos,ai-memory-vault').split(',').map((s) => s.trim()).filter(Boolean);
const MARKER = '.vault-export';
const ASSET_EXT = /\.(png|jpe?g|gif|webp|svg|avif)$/i;
const SECRET_RE = /(api[_-]?key|secret|passw(or)?d|heslo|token|sk-[A-Za-z0-9]{16,}|ghp_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|[\w.+-]+@[\w-]+\.[\w.-]+|\+420\s?\d{3})/i;

const ignore = new Set([...DEFAULT_IGNORE, ...EXCLUDE]);
const include = (rel) => /\.md$/i.test(rel) || ASSET_EXT.test(rel);
const skipNote = (n) => ['false', 'no'].includes(String(n.fm.share).toLowerCase());

// Refuse to wipe a directory we did not create.
async function cleanOut() {
  let existing = [];
  try { existing = await fs.readdir(OUT); } catch { /* does not exist */ }
  if (existing.length && !existing.includes(MARKER)) throw new Error(`${OUT} is not empty and has no ${MARKER} marker; refusing to delete it`);
  await fs.mkdir(OUT, { recursive: true });
  for (const name of existing.filter((n) => n !== '.vercel' && n !== 'node_modules')) await fs.rm(path.join(OUT, name), { recursive: true, force: true }); // keep OUT itself (may be a shell cwd)
  await fs.writeFile(path.join(OUT, MARKER), 'generated by export-static.mjs\n');
}

const copy = async (from, to) => { await fs.mkdir(path.dirname(to), { recursive: true }); await fs.copyFile(from, to); };

const idx = await buildIndex({ vault: VAULT, ignore, include, skipNote });
await cleanOut();

const notes = {};
for (const n of idx.notes.values()) notes[n.path] = notePayload(idx, n);
const db = scrubDeep({ index: indexPayload(idx), notes, tags: tagsPayload(idx), graph: graphPayload(idx) });
await fs.mkdir(path.join(OUT, 'data'), { recursive: true });
await fs.writeFile(path.join(OUT, 'data', 'vault.json'), JSON.stringify(db));

// preset index (compact index only; full dumps in data/presets/_local are never read)
const presets = await loadPresets(path.resolve(HERE, '..', '..'));
await fs.writeFile(path.join(OUT, 'data', 'presets.json'), JSON.stringify(presets));
await copy(path.resolve(HERE, '..', '..', 'knowledge', 'guides', 'next-step.json'), path.join(OUT, 'data', 'next-step.json'));
// Builds (full parameter detail of paid packs) stay local unless explicitly requested: node export-static.mjs --builds
let builds = 0;
if (process.argv.includes('--builds')) {
  await fs.mkdir(path.join(OUT, 'data', 'builds'), { recursive: true });
  for (const p of presets.presets) {
    const b = await loadBuild(path.resolve(HERE, '..', '..'), p.id);
    if (b) { await fs.writeFile(path.join(OUT, 'data', 'builds', `${p.id}.json`), JSON.stringify(b)); builds++; }
  }
}

// UI + vendor libs
for (const f of ['index.html', 'style.css', 'app.js', 'search-core.js', 'presets.html', 'presets.js', 'dal.html', 'dal.js', 'dashboard.html', 'dashboard.js', 'buildsheet.html', 'buildsheet.js', 'skin-samurai.css']) await copy(path.join(HERE, 'public', f), path.join(OUT, f));
for (const f of await fs.readdir(path.join(HERE, 'public', 'fonts'))) await copy(path.join(HERE, 'public', 'fonts', f), path.join(OUT, 'fonts', f));
await copy(path.join(HERE, 'node_modules/markdown-it/dist/markdown-it.min.js'), path.join(OUT, 'vendor/markdown-it.min.js'));
await copy(path.join(HERE, 'node_modules/d3/dist/d3.min.js'), path.join(OUT, 'vendor/d3.min.js'));

// images that survived the allowlist
const assets = idx.rels.filter((r) => ASSET_EXT.test(r));
for (const r of assets) await copy(path.join(VAULT, r), path.join(OUT, 'files', r));

// password gate + project config
await copy(path.join(HERE, 'deploy', 'middleware.js'), path.join(OUT, 'middleware.js'));
await copy(path.join(HERE, 'deploy', 'package.json'), path.join(OUT, 'package.json'));
await copy(path.join(HERE, 'deploy', 'vercel.json'), path.join(OUT, 'vercel.json'));
await copy(path.join(HERE, 'deploy', '.vercelignore'), path.join(OUT, '.vercelignore'));

// report
let brokenOut = 0;
const excludedTargets = new Set();
for (const n of idx.notes.values()) for (const [t, r] of Object.entries(n.links)) if (!r) { brokenOut++; excludedTargets.add(t); }
const hits = [];
for (const n of idx.notes.values()) {
  n.body.split('\n').forEach((line, i) => { if (SECRET_RE.test(line)) hits.push(`${n.path}:${i + 1}  ${line.trim().slice(0, 100)}`); });
}
const size = (await fs.stat(path.join(OUT, 'data', 'vault.json'))).size;
console.log(`Exported from: ${VAULT}`);
console.log(`Excluded dirs: ${EXCLUDE.join(', ') || '-'}   (share:false notes honored)`);
console.log(`Preset builds in export: ${builds}${builds ? '  (!! paid-pack detail, shared behind the password)' : ' (local only)'}`);
console.log(`Notes: ${idx.notes.size}, images: ${assets.length}, vault.json: ${(size / 1024).toFixed(0)} KB`);
console.log(`Links to anything outside the export (shown as dead links): ${brokenOut} (${excludedTargets.size} distinct targets)`);
console.log(`Output: ${OUT}`);
if (hits.length) {
  console.log(`\n!! ${hits.length} lines match the secret/PII scan — review before deploying:`);
  hits.slice(0, 40).forEach((h) => console.log('  ' + h));
  if (hits.length > 40) console.log(`  … +${hits.length - 40} more`);
} else console.log('\nSecret/PII scan: no matches.');
